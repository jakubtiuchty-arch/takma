import type { RibbonSeries } from './transfer-ribbon-series'
import { satoRibbonProducts } from './sato-ribbon-products'
import { satoPrintersForRibbon, satoRibbonPrinters, SATO_PRINTER_GROUP_LABELS, type SatoPrinterGroup } from './sato-ribbon-printers'

type Linia = 'Value' | 'Flex' | 'Flow'

const DATA = '2026-10-31'
const BRAK_DRUKAREK_ZEBRA = { desktop: [], midRange: [], industrial: [], mobile: [] }

/** Drukarki SATO, do których pasuje co najmniej jeden rozmiar serii (kolejność jak w tabeli). */
function grupyDrukarek(productId: string, linia: Linia): RibbonSeries['printerGroups'] {
  const warianty = satoRibbonProducts.find(p => p.id === productId)?.variants ?? []
  const modele = new Set(warianty.flatMap(w => satoPrintersForRibbon(w, linia).map(p => p.model)))
  return (Object.keys(SATO_PRINTER_GROUP_LABELS) as SatoPrinterGroup[])
    .map(grupa => ({
      label: SATO_PRINTER_GROUP_LABELS[grupa],
      models: satoRibbonPrinters
        .filter(p => p.group === grupa && modele.has(p.model))
        .flatMap(p => (p.links.length > 0 ? p.links.map(l => ({ name: l.name, href: l.href })) : [{ name: p.model }])),
    }))
    .filter(g => g.models.length > 0)
}

function karta(seria: string, plik: string) {
  return [
    { name: `Karta techniczna SATO ${seria} (EN)`, type: 'datasheet', url: `/datasheets/${plik}`, size: '0,2 MB' },
    { name: 'Katalog taśm SATO 2026 (PL)', type: 'pdf', url: '/datasheets/sato-ribbons-catalogue-pl.pdf', size: '2,9 MB' },
  ]
}

