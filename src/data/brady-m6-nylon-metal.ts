// Numery M6 podane w `zM710` działają w M710 bez adaptera (zgodnie z danymi o zgodności drukarek).
const zDrukarka = (warianty: ProductVariant[], zM710: string[] = []): ProductVariant[] =>
  warianty.map((w) => ({
    ...w,
    attributes: {
      ...w.attributes,
      Drukarka: /^B?M7/.test(w.partNumber) ? 'M710' : /^BM/.test(w.partNumber) || zM710.includes(w.partNumber) ? 'M610, M611, M710' : 'M610, M611',
    },
  }))

